import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
import { ROUTES, SITE_URL, canonicalFor } from './src/data/seo.js'

/**
 * DEPLOY TARGET — GitHub Pages on the custom domain kalapritidesigns.com.
 *
 * Because the site is served from the domain apex rather than a repository
 * subpath, the base is "/". It is read from VITE_BASE so a one-off preview
 * build can still be produced for stackified.github.io/kalapriti/ without
 * editing this file — hardcoding the base is what broke this site twice.
 *
 * Every asset URL comes from `asset()` in src/data/site.js, which reads
 * import.meta.env.BASE_URL. Vite rewrites the favicon and hero preload inside
 * index.html automatically, so nothing there needs touching either.
 */
const BASE = process.env.VITE_BASE || '/'

/**
 * GitHub Pages performs no server-side rewrites, so a deep link such as
 * /services is answered with 404.html. That file encodes the requested path
 * into a query string and bounces to index.html, where a snippet restores the
 * real URL before React mounts.
 *
 * `pathSegmentsToKeep` must equal the number of path segments in the base — 0
 * on the apex domain, 1 under /kalapriti/. Generating the file here rather than
 * keeping a static copy in public/ means the two can never drift apart.
 */
function ghPagesSpaFallback(base) {
  const segments = base.split('/').filter(Boolean).length
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <title>Kalapriti Designs</title>
    <script>
      // GENERATED by vite.config.js — do not edit by hand.
      var pathSegmentsToKeep = ${segments}
      var l = window.location
      l.replace(
        l.protocol + '//' + l.hostname + (l.port ? ':' + l.port : '') +
        l.pathname.split('/').slice(0, 1 + pathSegmentsToKeep).join('/') + '/?/' +
        l.pathname.slice(1).split('/').slice(pathSegmentsToKeep).join('/').replace(/&/g, '~and~') +
        (l.search ? '&' + l.search.slice(1).replace(/&/g, '~and~') : '') +
        l.hash
      )
    </script>
  </head>
  <body></body>
</html>
`
}

/**
 * PER-ROUTE HTML.
 *
 * The app is a single-page build, so without this every URL serves one head:
 * one title, one description, one Open Graph block. Google would see five
 * pages wearing the same name, and a link shared on WhatsApp would preview as
 * the homepage whichever page was shared.
 *
 * So after the bundle is written, each route gets its own copy of index.html
 * with its own head. Nothing is rendered server-side — the body is the same
 * empty root div, and React boots and takes over exactly as before. The only
 * difference is the handful of tags a crawler or a link scraper reads before
 * it stops, and those are the ones that were wrong.
 *
 * Two files per route, deliberately:
 *   dist/services.html        — GitHub Pages serves this at /services
 *   dist/services/index.html  — and this at /services/
 * Both carry the same canonical, so the duplicate collapses to one URL. Which
 * form Pages prefers is not worth guessing at when both cost 4kB.
 */
function renderRouteHtml(shell, route) {
  const url = canonicalFor(route.path)
  const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;')

  let html = shell
  const sub = (pattern, replacement, label) => {
    if (!pattern.test(html)) {
      throw new Error(
        `per-route SEO: no ${label} tag in index.html to rewrite for ${route.path}. ` +
        `The shell changed shape — update vite.config.js rather than shipping a wrong head.`
      )
    }
    html = html.replace(pattern, replacement)
  }

  sub(/<title>[\s\S]*?<\/title>/, `<title>${esc(route.title)}</title>`, 'title')
  sub(
    /(<meta\s+name="description"\s+content=")[\s\S]*?(")/,
    `$1${esc(route.description)}$2`,
    'description',
  )
  sub(/(<link rel="canonical" href=")[^"]*(")/, `$1${url}$2`, 'canonical')
  sub(/(<meta property="og:title" content=")[\s\S]*?(")/, `$1${esc(route.title)}$2`, 'og:title')
  sub(
    /(<meta\s+property="og:description"\s+content=")[\s\S]*?(")/,
    `$1${esc(route.description)}$2`,
    'og:description',
  )
  sub(/(<meta property="og:url" content=")[^"]*(")/, `$1${url}$2`, 'og:url')

  if (route.noindex) {
    html = html.replace('</head>', '    <meta name="robots" content="noindex, follow" />\n  </head>')
  }
  return html
}

function renderSitemap(routes) {
  const urls = routes
    .filter((r) => !r.noindex)
    .map((r) => `  <url><loc>${canonicalFor(r.path)}</loc><priority>${r.priority}</priority></url>`)
    .join('\n')
  return `<?xml version="1.0" encoding="UTF-8"?>
<!--
  GENERATED by vite.config.js from src/data/seo.js — do not edit by hand.
  Routes marked noindex are deliberately absent.
-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`
}

function githubPagesArtifacts({ base }) {
  return {
    name: 'kalapriti-gh-pages-artifacts',
    apply: 'build',
    // closeBundle runs after publicDir has been copied, so this always wins.
    closeBundle() {
      const dist = resolve(import.meta.dirname, 'dist')
      writeFileSync(resolve(dist, '404.html'), ghPagesSpaFallback(base))

      const shell = readFileSync(resolve(dist, 'index.html'), 'utf8')
      for (const route of ROUTES) {
        const html = renderRouteHtml(shell, route)
        if (route.path === '/') {
          writeFileSync(resolve(dist, 'index.html'), html)
          continue
        }
        const slug = route.path.replace(/^\//, '')
        writeFileSync(resolve(dist, `${slug}.html`), html)
        mkdirSync(resolve(dist, slug), { recursive: true })
        writeFileSync(resolve(dist, slug, 'index.html'), html)
      }

      // Generated from the same table as the pages, so the two cannot drift —
      // the old hand-maintained public/sitemap.xml had already gone stale.
      writeFileSync(resolve(dist, 'sitemap.xml'), renderSitemap(ROUTES))
      writeFileSync(
        resolve(dist, 'robots.txt'),
        `User-agent: *\nAllow: /\n\nSitemap: ${SITE_URL}/sitemap.xml\n`,
      )
    },
  }
}

export default defineConfig({
  base: BASE,
  plugins: [react(), githubPagesArtifacts({ base: BASE })],
})
